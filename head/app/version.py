"""Отпечаток исходников, чтобы заметить контейнер, собранный из старого кода.

Dockerfile копирует `head/` внутрь образа. Значит `docker compose up -d`
без `--build` поднимает прежний код, даже когда в рабочем каталоге уже
новый: `git pull` проходит, контейнер перезапускается, и всё выглядит
обновлённым. Ошибка при этом остаётся прежней — с тем же номером строки,
что и до исправления, и это единственная подсказка.

Отпечаток считается одинаково с двух сторон: голова печатает свой изнутри
контейнера, меню считает его же по рабочему каталогу. Разошлись — образ
устарел.

Модуль намеренно без зависимостей: menu.py живёт на хосте, вне окружения
головы, и подгружает его отсюда напрямую. Одна реализация вместо двух,
которые обязаны совпадать до байта и однажды разойдутся.
"""

from __future__ import annotations

import hashlib
from pathlib import Path


def source_fingerprint(package_root: str | Path) -> str:
    """Хэш всех .py пакета `app`, устойчивый к порядку обхода файловой системы.

    Путь входит в хэш вместе с содержимым: переименованный файл — это тоже
    изменение кода, а по одному лишь содержимому оно бы потерялось.
    """
    root = Path(package_root)
    digest = hashlib.sha256()
    for path in sorted(root.rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        digest.update(str(path.relative_to(root)).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()[:12]
